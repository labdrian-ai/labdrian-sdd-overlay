package installer_test

// The registry pins of `repair-sdd-registry` (registry_pins_world_test.go has the world): the SDD
// executor rows the script puts in a project's .atl/skill-registry.md, which it keeps through the
// regeneration of the registry by gentle-ai. Each pin is the exit code and both streams of a run,
// and the registry it left (its mode and its text).

import (
	"os"
	"path/filepath"
	"strings"
	"testing"
)

// gentleRegistry is a registry as gentle-ai writes it, with the rows of two skills it knows, a
// shared contracts table with a block the propagator owns, and the loading protocol.
const gentleRegistry = "# Skill Registry — proj\n" +
	"\n" +
	"Generated by gentle-ai skill-registry refresh.\n" +
	"\n" +
	"## Skills\n" +
	"\n" +
	"| Skill | Trigger / description | Scope | Path |\n" +
	"| --- | --- | --- | --- |\n" +
	"| `go-testing` | Go tests | user | `/skills/go-testing/SKILL.md` |\n" +
	"| `branch-pr` | Pull requests | user | `/skills/branch-pr/SKILL.md` |\n" +
	"\n" +
	"### Shared Contracts\n" +
	"\n" +
	"| Contract | Path | Applies |\n" +
	"| --- | --- | --- |\n" +
	"<!-- BEGIN: minimalism-contract-scope (auto-generated) -->\n" +
	"| minimalism-contract | skills/_shared/minimalism-contract.md | Inject ONLY into sdd-apply prompts. |\n" +
	"<!-- END: minimalism-contract-scope -->\n" +
	"\n" +
	"## Loading protocol\n" +
	"\n" +
	"1. Match task context and target files against the `Trigger / description` column.\n" +
	"2. Pass only the matching `Path` values to the subagent under `## Skills to load before work`.\n"

// staleRegistry is gentleRegistry after an earlier repair, with its rows out of date: the note
// the repair writes above the skills, a row for a skill the overlay no longer has, and a stale
// row for one it has.
const staleRegistry = "# Skill Registry — proj\n" +
	"\n" +
	"`sdd-*` phase skills are executor contracts. Gentle may skip them as user-invocable skills, but this registry keeps their paths visible so SDD delegation can resolve the existing installed files.\n" +
	"\n" +
	"## Skills\n" +
	"\n" +
	"| Skill | Trigger / description | Scope | Path |\n" +
	"| --- | --- | --- | --- |\n" +
	"| `go-testing` | Go tests | user | `/skills/go-testing/SKILL.md` |\n" +
	"| `sdd-apply` | stale | executor | `/old/sdd-apply/SKILL.md` |\n" +
	"| `sdd-ghost` | a skill the overlay has not got | executor | `/old/sdd-ghost/SKILL.md` |\n" +
	"\n" +
	"## Loading protocol\n" +
	"\n" +
	"1. Match.\n"

// pinRepair pins a run of a command that repairs the registry of the project: the run, then the
// registry it left.
func pinRepair(t *testing.T, w *pinWorld, name string, run pinRun) {
	t.Helper()
	pin(t, name, pinRunText(run)+w.showRegistry(w.registryPath()))
}

func TestRegistryPins_RepairWritesTheRowsOfTheInstalledExecutors(t *testing.T) {
	descriptions := map[string]string{
		"sdd-apply":           `Apply the change`,
		"sdd-archive":         `"Archive | with a pipe"`,
		"sdd-design":          ``, // no description line at all
		"sdd-explore":         `   padded on both sides   `,
		"sdd-init":            `"quoted" and then more`,
		"sdd-onboard":         `'single quotes stay'`,
		"sdd-propose":         `>-`,
		"sdd-spec":            `say "hi"`,
		"sdd-tasks":           `\|already escaped`,
		"sdd-time-estimation": `trailing carriage return` + "\r",
		"sdd-verify":          `"`,
	}
	w := registryWorld(t)
	w.installExecutors("codex", func(name string) string { return descriptions[name] })
	// A description line is the first line that begins with the word, wherever it is in the file.
	w.installSkill("codex", "sdd-onboard", "# no frontmatter\n\ndescription: found in the body\ndescription: not this one\n")
	w.installSkill("codex", "sdd-explore", "---\nname: sdd-explore\ndescription:    padded on both sides   \ndescription: second\n---\n")

	run := w.runIn(w.project(), "repair-sdd-registry", "--no-refresh")
	pinRepair(t, w, "repair/new-registry-every-executor-installed", run)
}

func TestRegistryPins_RepairSaysWhichExecutorsAreNotInstalled(t *testing.T) {
	w := registryWorld(t)
	pinRepair(t, w, "repair/new-registry-nothing-installed",
		w.runIn(w.project(), "repair-sdd-registry", "--no-refresh"))
	w2 := registryWorld(t)
	w2.installSkill("codex", "sdd-apply", "---\ndescription: Apply\n---\n")
	w2.installSkill("codex", "sdd-verify", "---\ndescription: Verify\n---\n")
	// A directory where the skill file should be is no skill file.
	if err := os.MkdirAll(filepath.Join(w2.home, ".codex", "skills", "sdd-spec", "SKILL.md"), 0o755); err != nil {
		t.Fatal(err)
	}
	pinRepair(t, w2, "repair/new-registry-some-installed",
		w2.runIn(w2.project(), "repair-sdd-registry", "--no-refresh"))
}

func TestRegistryPins_RepairReplacesTheRowsOfAnExistingRegistryAndAddsABlankLineEachTime(t *testing.T) {
	for _, tc := range []struct{ name, registry string }{
		{"as-gentle-wrote-it", gentleRegistry},
		{"after-an-earlier-repair", staleRegistry},
	} {
		t.Run(tc.name, func(t *testing.T) {
			w := registryWorld(t)
			for _, name := range []string{"sdd-apply", "sdd-spec", "sdd-verify"} {
				w.installSkill("codex", name, "---\ndescription: Runs "+name+"\n---\n")
			}
			w.writeRegistry(tc.registry)
			pinRepair(t, w, "repair/existing-"+tc.name, w.runIn(w.project(), "repair-sdd-registry", "--no-refresh"))
			// Not idempotent, and pinned as it is: the note and the rows are written again, and the
			// blank line each is followed by is kept from the run before, so every repair adds two.
			pinRepair(t, w, "repair/existing-"+tc.name+"-again", w.runIn(w.project(), "repair-sdd-registry", "--no-refresh"))
		})
	}
}

func TestRegistryPins_RepairKeepsWhatItDoesNotKnowAndRemovesWhatLooksLikeItsRows(t *testing.T) {
	registry := "## Skills\n" +
		"| `sdd-spec` | a row of the overlay | executor | `/x` |\n" + // removed
		"| `sdd-spec`| no space before the bar | executor | `/x` |\n" + // kept: the pattern wants a space
		"| sdd-spec | no backticks | executor | `/x` |\n" + // kept
		"|  `sdd-spec` | two spaces before | executor | `/x` |\n" + // kept
		"| `sdd-a` | a name with a bar | executor | `/x` |\n" + // removed, and the name is not one of the overlay's
		"| `sdd-` | empty tail | executor | `/x` |\n" + // kept: the pattern wants a name
		"| `sdd-spec` and more\n" + // kept
		"  | `sdd-spec` | indented | executor | `/x` |\n" + // kept
		"## Loading protocol\n"
	w := registryWorld(t)
	w.installSkill("codex", "sdd-apply", "---\ndescription: Apply\n---\n")
	w.writeRegistry(registry)
	pinRepair(t, w, "repair/rows-that-look-like-executor-rows",
		w.runIn(w.project(), "repair-sdd-registry", "--no-refresh"))
}

