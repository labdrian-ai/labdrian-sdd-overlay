func TestRegistryPins_RepairReadsTheSkillsOfTheTargetItIsToldOf(t *testing.T) {
	for _, target := range []string{"claude", "opencode", "codex"} {
		t.Run(target, func(t *testing.T) {
			w := registryWorld(t)
			for _, other := range []string{"claude", "opencode", "codex"} {
				w.installSkill(other, "sdd-apply", "---\ndescription: Apply for "+other+"\n---\n")
			}
			pinRepair(t, w, "repair/target-"+target,
				w.runIn(w.project(), "repair-sdd-registry", "--no-refresh", "--target", target))
		})
	}
	t.Run("by default", func(t *testing.T) {
		w := registryWorld(t)
		w.installSkill("codex", "sdd-apply", "---\ndescription: Apply for codex\n---\n")
		pinRepair(t, w, "repair/target-by-default", w.runIn(w.project(), "repair-sdd-registry", "--no-refresh"))
	})
}

func TestRegistryPins_RepairNamesTheProjectAfterItsDirectory(t *testing.T) {
	w := registryWorld(t)
	run := w.runIn(w.project(), "repair-sdd-registry", "--no-refresh", "--cwd", ".")
	pinRepair(t, w, "repair/cwd-dot", run)

	w = registryWorld(t)
	run = w.runIn(w.home, "repair-sdd-registry", "--no-refresh", "--cwd", "proj")
	pinRepair(t, w, "repair/cwd-relative", run)

	w = registryWorld(t)
	run = w.runIn(w.home, "repair-sdd-registry", "--no-refresh", "--cwd", w.project()+"/")
	pinRepair(t, w, "repair/cwd-trailing-slash", run)

	w = registryWorld(t)
	run = w.runIn(w.home, "repair-sdd-registry", "--no-refresh", "--cwd", w.project(), "--cwd", w.home)
	pin(t, "repair/cwd-twice", pinRunText(run)+w.showRegistry(filepath.Join(w.home, ".atl", "skill-registry.md")))
}

// HOME is where the script keeps the skills of a target, and it joins paths by concatenation: a HOME
// that ends with a slash gives the rows, and the warnings, a path with two slashes in the middle.
// It is pinned as the script did it; the engine joins the skills root and the name of a skill the
// same way and does not clean the path it is handed.
func TestRegistryPins_RepairKeepsTheSlashesOfAHomeThatEndsWithOne(t *testing.T) {
	w := registryWorld(t)
	w.installSkill("codex", "sdd-apply", "---\ndescription: Apply\n---\n")
	w.env = append(w.env, "HOME="+w.home+"/") // the last entry of a name is the one a run gets
	pinRepair(t, w, "repair/home-with-a-trailing-slash", w.runIn(w.project(), "repair-sdd-registry", "--no-refresh"))
}

func TestRegistryPins_RepairReplacesARegistryThatIsASymbolicLink(t *testing.T) {
	w := registryWorld(t)
	target := filepath.Join(w.home, "elsewhere", "registry.md")
	w.write(w.home, "elsewhere/registry.md", gentleRegistry)
	if err := os.MkdirAll(filepath.Dir(w.registryPath()), 0o755); err != nil {
		t.Fatal(err)
	}
	if err := os.Symlink(target, w.registryPath()); err != nil {
		t.Fatal(err)
	}
	run := w.runIn(w.project(), "repair-sdd-registry", "--no-refresh")
	pinRepair(t, w, "repair/symbolic-link", run)
	pin(t, "repair/symbolic-link-target", w.showRegistry(target))
}

func TestRegistryPins_RepairRefusesWhatItIsNotAskedRight(t *testing.T) {
	for _, tc := range []struct {
		name string
		args []string
	}{
		{"unknown-option", []string{"--frobnicate"}},
		{"unknown-target", []string{"--target", "vim"}},
		{"package-target", []string{"--target", "pi"}},
		{"target-without-a-value", []string{"--target"}},
		{"target-with-an-empty-value", []string{"--target", ""}},
		{"cwd-without-a-value", []string{"--cwd"}},
		{"cwd-that-is-not-a-directory", []string{"--cwd", "$HOME/not-there"}},
		{"cwd-that-is-a-file", []string{"--cwd", "$HOME/proj/.atl/file"}},
	} {
		t.Run(tc.name, func(t *testing.T) {
			w := registryWorld(t)
			w.write(w.project(), ".atl/file", "x")
			args := []string{"repair-sdd-registry", "--no-refresh"}
			for _, a := range tc.args {
				args = append(args, strings.ReplaceAll(a, "$HOME", w.home))
			}
			pinRepair(t, w, "repair/refused-"+tc.name, w.runIn(w.project(), args...))
		})
	}
}
