package skillregistry

import (
	"regexp"
	"strings"
)

// Header is what the generated head of the registry says.
type Header struct {
	// Project is the name of the project: the directory the registry is in.
	Project string
	// Sources are the labels of the directories scanned that exist, in order.
	Sources []string
	// Date is the day the registry is written, as YYYY-MM-DD.
	Date string
}

// UnrecognizedError is a registry whose skills table cannot be found, so that nothing is known of
// where the rows go. The registry is left as it is.
type UnrecognizedError struct {
	Reason string
}

func (e *UnrecognizedError) Error() string { return "registry not recognized: " + e.Reason }

// The text of the registry that is the same for every project.
const (
	titlePrefix   = "# Skill Registry"
	commentPrefix = "<!-- Auto-generated by"
	datePrefix    = "Last updated:"

	sourcesHeading  = "## Sources scanned"
	contractHeading = "## Contract"
	skillsHeading   = "## Skills"

	contractUse = "**Delegator use only.** This registry is an index, not a summary. Any agent that launches subagents reads it to select relevant skills, then passes exact `SKILL.md` paths for the subagent to read before work."
	contractSrc = "`SKILL.md` remains the source of truth. Do not inject generated summaries or compact rules by default; pass paths so subagents load the full runtime contract and preserve author intent."

	tableHeader        = "| Skill | Trigger / description | Scope | Path |"
	tableSeparator     = "| --- | --- | --- | --- |"
	executorNotePrefix = "`sdd-*` phase skills are executor contracts."
)

// generatedRow is a row as Row.Line writes it for a skill of a source: a name and a path in backticks
// around a description, and the scope project or user. A row with the scope executor is not matched;
// it is dropped (executorScopeRow).
var generatedRow = regexp.MustCompile("^\\| `.+` \\| .* \\| (project|user) \\| `.+` \\|$")

const generatedComment = "<!-- Auto-generated by labdrian skill-registry refresh. Run `labdrian skill-registry refresh --force` to regenerate. -->"

// protocol is the loading protocol a registry that has none starts with.
var protocol = []string{
	"## Loading protocol",
	"",
	"1. Match task context and target files against the `Trigger / description` column.",
	"2. Pass only the matching `Path` values to the subagent under `## Skills to load before work`.",
	"3. Instruct the subagent to read those exact `SKILL.md` files before reading, writing, reviewing, testing, or creating artifacts.",
	"4. If no matching skill exists, proceed without project skill injection and report `skill_resolution: none`.",
}

// Compose writes the registry of a project: its generated head (title, the comment that names the
// command, the date, the sources scanned and the contract), the skills table with rows, and, below
// the table, everything the existing registry holds from the line after its rows, byte for byte: the
// Hermes section, the loading protocol, the blocks `propagate` writes and every other foreign line. Of
// the existing head, only the generated lines are replaced; any other line of it is kept, in the same
// order, below the generated head. Two things written by the repair of the sdd-* executors, whose writer
// is gone, are migrated away: every row with the scope executor in the table block (the rows of the
// table and the lines after them up to the first heading or comment line, so a Hermes section or a
// section below a heading is never touched), and the executor note of the head with the one blank line
// after it. A second compose changes nothing. An existing
// registry that has no skills table is refused (an *UnrecognizedError) and nothing is returned; an
// empty one is a project's first, written whole with the loading protocol.
func Compose(existing string, h Header, rows []Row) (string, error) {
	var out []string
	out = append(out, head(h)...)
	rowLines := make([]string, len(rows))
	for i, row := range rows {
		rowLines[i] = row.Line()
	}
	if existing == "" {
		out = append(out, skillsHeading, "", tableHeader, tableSeparator)
		out = append(out, rowLines...)
		out = append(out, "")
		out = append(out, protocol...)
		out = append(out, "")
		return strings.Join(out, "\n"), nil
	}

	lines := strings.Split(existing, "\n")
	skills := indexOf(lines, skillsHeading)
	if skills < 0 {
		return "", &UnrecognizedError{Reason: "it has no '" + skillsHeading + "' section"}
	}
	header := -1
	for i := skills + 1; i < len(lines) && !strings.HasPrefix(lines[i], "## "); i++ {
		if strings.HasPrefix(lines[i], "| Skill |") {
			header = i
			break
		}
	}
	if header < 0 || header+1 >= len(lines) || !strings.HasPrefix(lines[header+1], "| --- |") {
		return "", &UnrecognizedError{Reason: "its '" + skillsHeading + "' section has no table"}
	}
	first := header + 2
	end := first
	// What stays of the lines that touch the table: every one that is not a row of a skill the
	// generator writes, in order, but for the executor-scope rows, which are dropped: a table of someone
	// else written right under the rows is among them.
	var kept []string
	for ; end < len(lines) && strings.HasPrefix(lines[end], "| "); end++ {
		if !generatedRow.MatchString(lines[end]) && !executorScopeRow(lines[end]) {
			kept = append(kept, lines[end])
		}
	}

	out = out[:0]
	out = append(out, headLines(withoutExecutorNote(lines[:skills]), h)...)
	out = append(out, lines[skills:first]...)
	out = append(out, rowLines...)
	out = append(out, kept...)
	// The migration reaches the block of the table: the lines after it up to the first heading or
	// comment line. A section someone else owns (Hermes checks its own bytes by a hash) starts with
	// one of those, and is kept byte for byte.
	block := true
	for _, line := range lines[end:] {
		if strings.HasPrefix(line, "#") || strings.HasPrefix(line, "<!--") {
			block = false
		}
		if block && executorScopeRow(line) {
			continue
		}
		out = append(out, line)
	}
	return strings.Join(out, "\n"), nil
}

// executorScopeRow says whether line is a row with the scope executor, as the repair of the sdd-* skills
// that is gone wrote them. Its writer is gone and the paths in it are dead, so the migration drops it.
func executorScopeRow(line string) bool {
	return strings.HasPrefix(line, "| `") && strings.Contains(line, " | executor | ")
}

// withoutExecutorNote is the lines of a head without the note the repair wrote above the skills, the line
// that starts with the executor note prefix, and the one blank line that follows it.
func withoutExecutorNote(lines []string) []string {
	out := make([]string, 0, len(lines))
	for i := 0; i < len(lines); i++ {
		if strings.HasPrefix(lines[i], executorNotePrefix) {
			if i+1 < len(lines) && lines[i+1] == "" {
				i++
			}
			continue
		}
		out = append(out, lines[i])
	}
	return out
}

// LastUpdated is the date the registry says it was written, or "" when it says none.
func LastUpdated(registry string) string {
	for _, line := range strings.Split(registry, "\n") {
		if rest, ok := strings.CutPrefix(line, datePrefix); ok {
			return strings.TrimSpace(rest)
		}
	}
	return ""
}

// head is the generated head, ending with the blank line that comes before the next section.
func head(h Header) []string {
	out := []string{
		titlePrefix + " — " + h.Project,
		"",
		generatedComment,
		"",
		datePrefix + " " + h.Date,
		"",
		sourcesHeading,
		"",
	}
	for _, source := range h.Sources {
		out = append(out, "- "+source)
	}
	return append(out, "", contractHeading, "", contractUse, "", contractSrc, "")
}

// headLines is the head of the registry whose existing head is lines. When the existing head has every
// generated part (the title, the comment, the date, the sources scanned and the contract) they are
// replaced where they are and every other line, a blank one included, stays byte for byte, so a head
// the repair of the executor rows once changed is not rewritten by a refresh. Otherwise the head is
// the generated one, followed by the lines of the existing head that are none of the generated parts.
func headLines(lines []string, h Header) []string {
	if !hasEveryGeneratedPart(lines) {
		return append(head(h), foreignHead(lines)...)
	}
	var out []string
	// sources is 0 outside the sources section, 1 right after its heading (the blank line there is
	// written with the heading) and 2 among its bullets, which are written with the heading too.
	sources := 0
	for _, line := range lines {
		switch {
		case sources == 1 && line == "":
			sources = 2
		case sources == 2 && strings.HasPrefix(line, "- "):
		default:
			sources = 0
			switch {
			case strings.HasPrefix(line, titlePrefix):
				out = append(out, titlePrefix+" — "+h.Project)
			case strings.HasPrefix(line, commentPrefix):
				out = append(out, generatedComment)
			case strings.HasPrefix(line, datePrefix):
				out = append(out, datePrefix+" "+h.Date)
			case line == sourcesHeading:
				out = append(out, line, "")
				for _, source := range h.Sources {
					out = append(out, "- "+source)
				}
				sources = 1
			default:
				out = append(out, line)
			}
		}
	}
	return out
}

func hasEveryGeneratedPart(lines []string) bool {
	var title, comment, date, sources, contract bool
	for _, line := range lines {
		switch {
		case strings.HasPrefix(line, titlePrefix):
			title = true
		case strings.HasPrefix(line, commentPrefix):
			comment = true
		case strings.HasPrefix(line, datePrefix):
			date = true
		case line == sourcesHeading:
			sources = true
		case line == contractHeading:
			contract = true
		}
	}
	return title && comment && date && sources && contract
}

// foreignHead is the lines of the head of an existing registry that the generated head does not
// replace, in order: every line that is not the title, the comment, the date, the sources scanned
// or the contract. A blank line is kept only when it follows a line that is kept.
func foreignHead(lines []string) []string {
	var out []string
	inSources := false
	afterKept := false
	for _, line := range lines {
		switch {
		case strings.HasPrefix(line, titlePrefix), strings.HasPrefix(line, commentPrefix), strings.HasPrefix(line, datePrefix):
			inSources, afterKept = false, false
		case line == sourcesHeading:
			inSources, afterKept = true, false
		case inSources && strings.HasPrefix(line, "- "):
			afterKept = false
		case line == contractHeading, line == contractUse, line == contractSrc:
			inSources, afterKept = false, false
		case line == "":
			if afterKept {
				out = append(out, line)
			}
			afterKept = false
		default:
			inSources = false
			out = append(out, line)
			afterKept = true
		}
	}
	return out
}

func indexOf(lines []string, want string) int {
	for i, line := range lines {
		if line == want {
			return i
		}
	}
	return -1
}
