package skillregistry

import (
	"strings"
)

// Header is what the generated head of the registry says.
type Header struct {
	// Project is the name of the project: the directory the registry is in.
	Project string
	// Sources are the labels of the directories scanned that exist, in order.
	Sources []string
	// Date is the day the registry is written, as YYYY-MM-DD.
	Date string
}

// UnrecognizedError is a registry whose skills table cannot be found, so that nothing is known of
// where the rows go. The registry is left as it is.
type UnrecognizedError struct {
	Reason string
}

func (e *UnrecognizedError) Error() string { return "registry not recognized: " + e.Reason }

// The text of the registry that is the same for every project.
const (
	titlePrefix   = "# Skill Registry"
	commentPrefix = "<!-- Auto-generated by"
	datePrefix    = "Last updated:"

	sourcesHeading  = "## Sources scanned"
	contractHeading = "## Contract"
	skillsHeading   = "## Skills"

	contractUse = "**Delegator use only.** This registry is an index, not a summary. Any agent that launches subagents reads it to select relevant skills, then passes exact `SKILL.md` paths for the subagent to read before work."
	contractSrc = "`SKILL.md` remains the source of truth. Do not inject generated summaries or compact rules by default; pass paths so subagents load the full runtime contract and preserve author intent."

	tableHeader    = "| Skill | Trigger / description | Scope | Path |"
	tableSeparator = "| --- | --- | --- | --- |"
	executorRow    = "| `sdd-"
)

const generatedComment = "<!-- Auto-generated by labdrian skill-registry refresh. Run `labdrian skill-registry refresh --force` to regenerate. -->"

// protocol is the loading protocol a registry that has none starts with.
var protocol = []string{
	"## Loading protocol",
	"",
	"1. Match task context and target files against the `Trigger / description` column.",
	"2. Pass only the matching `Path` values to the subagent under `## Skills to load before work`.",
	"3. Instruct the subagent to read those exact `SKILL.md` files before reading, writing, reviewing, testing, or creating artifacts.",
	"4. If no matching skill exists, proceed without project skill injection and report `skill_resolution: none`.",
}

// Compose writes the registry of a project: its generated head (title, the comment that names the
// command, the date, the sources scanned and the contract), the skills table with rows, and, below
// the table, everything the existing registry holds from the line after its rows, byte for byte: the
// executor rows and the note above them, the Hermes section, the loading protocol and the blocks
// `propagate` writes. Of the existing head, only the generated lines are replaced; any other line of
// it (the executor note) is kept, in the same order, below the generated head. An existing
// registry that has no skills table is refused (an *UnrecognizedError) and nothing is returned; an
// empty one is a project's first, written whole with the loading protocol.
func Compose(existing string, h Header, rows []Row) (string, error) {
	var out []string
	out = append(out, head(h)...)
	rowLines := make([]string, len(rows))
	for i, row := range rows {
		rowLines[i] = row.Line()
	}
	if existing == "" {
		out = append(out, skillsHeading, "", tableHeader, tableSeparator)
		out = append(out, rowLines...)
		out = append(out, "")
		out = append(out, protocol...)
		out = append(out, "")
		return strings.Join(out, "\n"), nil
	}

	lines := strings.Split(existing, "\n")
	skills := indexOf(lines, skillsHeading)
	if skills < 0 {
		return "", &UnrecognizedError{Reason: "it has no '" + skillsHeading + "' section"}
	}
	header := -1
	for i := skills + 1; i < len(lines) && !strings.HasPrefix(lines[i], "## "); i++ {
		if strings.HasPrefix(lines[i], "| Skill |") {
			header = i
			break
		}
	}
	if header < 0 || header+1 >= len(lines) || !strings.HasPrefix(lines[header+1], "| --- |") {
		return "", &UnrecognizedError{Reason: "its '" + skillsHeading + "' section has no table"}
	}
	first := header + 2
	end := first
	var executors []string
	for ; end < len(lines) && strings.HasPrefix(lines[end], "| "); end++ {
		if strings.HasPrefix(lines[end], executorRow) {
			executors = append(executors, lines[end])
		}
	}

	out = append(out, foreignHead(lines[:skills])...)
	out = append(out, lines[skills:first]...)
	out = append(out, rowLines...)
	out = append(out, executors...)
	out = append(out, lines[end:]...)
	return strings.Join(out, "\n"), nil
}

// LastUpdated is the date the registry says it was written, or "" when it says none.
func LastUpdated(registry string) string {
	for _, line := range strings.Split(registry, "\n") {
		if rest, ok := strings.CutPrefix(line, datePrefix); ok {
			return strings.TrimSpace(rest)
		}
	}
	return ""
}

// head is the generated head, ending with the blank line that comes before the next section.
func head(h Header) []string {
	out := []string{
		titlePrefix + " — " + h.Project,
		"",
		generatedComment,
		"",
		datePrefix + " " + h.Date,
		"",
		sourcesHeading,
		"",
	}
	for _, source := range h.Sources {
		out = append(out, "- "+source)
	}
	return append(out, "", contractHeading, "", contractUse, "", contractSrc, "")
}

// foreignHead is the lines of the head of an existing registry that the generated head does not
// replace, in order: every line that is not the title, the comment, the date, the sources scanned
// or the contract. A blank line is kept only when it follows a line that is kept.
func foreignHead(lines []string) []string {
	var out []string
	inSources := false
	afterKept := false
	for _, line := range lines {
		switch {
		case strings.HasPrefix(line, titlePrefix), strings.HasPrefix(line, commentPrefix), strings.HasPrefix(line, datePrefix):
			inSources, afterKept = false, false
		case line == sourcesHeading:
			inSources, afterKept = true, false
		case inSources && strings.HasPrefix(line, "- "):
			afterKept = false
		case line == contractHeading, line == contractUse, line == contractSrc:
			inSources, afterKept = false, false
		case line == "":
			if afterKept {
				out = append(out, line)
			}
			afterKept = false
		default:
			inSources = false
			out = append(out, line)
			afterKept = true
		}
	}
	return out
}

func indexOf(lines []string, want string) int {
	for i, line := range lines {
		if line == want {
			return i
		}
	}
	return -1
}
