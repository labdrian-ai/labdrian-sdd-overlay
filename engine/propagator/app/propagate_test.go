const registryPath = "/project/.atl/skill-registry.md"

const contractText = "---\napplies_to_phases: [sdd-tasks, sdd-apply]\nexcluded_phases: [sdd-propose]\n" +
	"injection_point: \"## Skills to load before work\"\n---\n# A contract\n"

const bareRegistry = "# Skill Registry\n\n### Shared Contracts\n\n| Artifact | Path | Description |\n|---|---|---|\n| other | other.md | Other |\n"

// foreign is what another tool leaves when it regenerates the registry whole.
const foreign = "# Skill Registry\n\nregenerated by another tool\n"

func request(c app.ContractSource) app.Request {
	return app.Request{Registry: registryPath, Contract: c, Config: propagator.Config{ContractPath: "skills/_shared/minimalism-contract.md"}}
}

// scoped is the registry the use case writes for bareRegistry.
func scoped(t *testing.T) string {
	t.Helper()
	doc, err := contract.Parse(contractText)
	if err != nil {
		t.Fatal(err)
	}
	out, changed, err := propagator.Propagate(bareRegistry, propagator.Config{ContractPath: "skills/_shared/minimalism-contract.md"}, doc)
	if err != nil || !changed {
		t.Fatalf("Propagate = %v, %v", changed, err)
	}
	return out
}

