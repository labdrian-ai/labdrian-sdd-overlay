func TestVerifiedForwardsAHardFailureAtOnce(t *testing.T) {
	for _, c := range []struct {
		name   string
		source *fakeContract
		store  func() *fakeStore
		want   any
	}{
		{"a contract that cannot be read", &fakeContract{err: errors.New("denied")}, func() *fakeStore { return newFakeStore(nil) }, new(*app.ContractReadError)},
		{"a contract that does not parse", &fakeContract{text: "nothing"}, func() *fakeStore { return newFakeStore(nil) }, new(*app.ContractParseError)},
		{"a registry that cannot be read", &fakeContract{text: contractText}, func() *fakeStore {
			s := newFakeStore(nil)
			s.script = []answer{fails("denied")}
			return s
		}, new(*app.RegistryReadError)},
		{"a registry that cannot be written", &fakeContract{text: contractText}, func() *fakeStore {
			s := newFakeStore(map[string]string{registryPath: bareRegistry})
			s.failOn[1] = errors.New("full")
			return s
		}, new(*app.RegistryWriteError)},
	} {
		store := c.store()
		_, err := app.New(store).PropagateVerified(request(c.source))
		if err == nil || !errors.As(err, c.want) {
			t.Errorf("%s: error %T %v, want %T", c.name, err, err, c.want)
		}
		if c.source.reads != 1 {
			t.Errorf("%s: the contract was read %d times, want 1 (no retry)", c.name, c.source.reads)
		}
	}
}

