// The parity test: testdata/registry_refresh_parity holds a project and a home of skills that cover
// every rule of `gentle-ai skill-registry refresh` 4.2.0, and the registry that gentle-ai wrote for
// them (expected.md), recorded once in a sandbox HOME with
//
//	gentle-ai skill-registry refresh --cwd <project> --force --no-gitignore
//
// with the paths of the sandbox replaced by {{PROJECT}} and {{HOME}}. The test runs `registry
// refresh` over a copy of the tree and compares the whole file. Two things differ, and the test
// names both: the comment that says which command generated the file, and the rows of the four
// skills whose description is a quoted value over several lines, which gentle-ai cut at the first
// line (L62) and `registry refresh` reads whole.

const parityDir = "testdata/registry_refresh_parity"

// quotedMultiline are the rows that differ from gentle-ai's: the description it recorded, and the
// whole one.
var quotedMultiline = map[string]struct{ gentle, whole string }{
	"multi":     {"first line", "first line second line third"},
	"sqmulti":   {"one", "one two"},
	"dqmulti":   {"a", "a b"},
	"crlfmulti": {"a", "a b"},
}

func copyTree(t *testing.T, from, to string) {
	t.Helper()
	err := filepath.WalkDir(from, func(path string, entry fs.DirEntry, err error) error {
		if err != nil {
			return err
		}
		rel, err := filepath.Rel(from, path)
		if err != nil {
			return err
		}
		target := filepath.Join(to, rel)
		if entry.IsDir() {
			return os.MkdirAll(target, 0o755)
		}
		data, err := os.ReadFile(path)
		if err != nil {
			return err
		}
		return os.WriteFile(target, data, 0o644)
	})
	if err != nil {
		t.Fatalf("copy %s: %v", from, err)
	}
}

func TestRegistryRefreshWritesWhatGentleWroteForTheSameSkills(t *testing.T) {
	w := newRefreshWorld(t)
	w.now = time.Date(2026, 11, 18, 3, 0, 0, 0, time.UTC) // the day the answer was recorded
	w.project = filepath.Join(w.root, "project")          // the recorded title names the directory
	copyTree(t, filepath.Join(parityDir, "project"), w.project)
	copyTree(t, filepath.Join(parityDir, "home"), w.home)
	w.markProject(t)

	p := w.run("--cwd", w.project, "--quiet")
	if p.out.String() != "" || p.err.String() != "" || len(p.exits) != 0 {
		t.Fatalf("run = stdout %q stderr %q exits %v", p.out.String(), p.err.String(), p.exits)
	}

	recorded, err := os.ReadFile(filepath.Join(parityDir, "expected.md"))
	if err != nil {
		t.Fatal(err)
	}
	want := string(recorded)
	// The rows of the whole-read descriptions are gentle-ai's cut ones in the record; the record
	// says so, and the test replaces them.
	for name, row := range quotedMultiline {
		cut := "| `" + name + "` | " + row.gentle + " | project |"
		if strings.Count(want, cut) != 1 {
			t.Fatalf("the record has no cut row for %s: %q", name, cut)
		}
		want = strings.Replace(want, cut, "| `"+name+"` | "+row.whole+" | project |", 1)
	}
	const gentleComment = "<!-- Auto-generated by gentle-ai skill-registry refresh. Run `gentle-ai skill-registry refresh --force` to regenerate. -->"
	const ourComment = "<!-- Auto-generated by labdrian skill-registry refresh. Run `labdrian skill-registry refresh --force` to regenerate. -->"
	if strings.Count(want, gentleComment) != 1 {
		t.Fatalf("the record has no gentle-ai comment")
	}
	want = strings.Replace(want, gentleComment, ourComment, 1)
	want = strings.ReplaceAll(want, "{{PROJECT}}", w.project)
	want = strings.ReplaceAll(want, "{{HOME}}", w.home)

	if got := w.read(t); got != want {
		t.Fatalf("registry differs from the record (first difference at line %d):\n%s", firstDifference(got, want), diffContext(got, want))
	}
}

func TestRegistryRefreshSkipsADirectoryThatIsNotAProjectInGentlesWords(t *testing.T) {
	w := newRefreshWorld(t)
	recorded, err := os.ReadFile(filepath.Join(parityDir, "nonproject-answer.txt"))
	if err != nil {
		t.Fatal(err)
	}

	p := w.run("--cwd", w.project)

	if want := strings.ReplaceAll(string(recorded), "{{DIR}}", w.project); p.out.String() != want || len(p.exits) != 0 {
		t.Fatalf("stdout = %q, want %q", p.out.String(), want)
	}
}

func firstDifference(a, b string) int {
	la, lb := strings.Split(a, "\n"), strings.Split(b, "\n")
	for i := 0; i < len(la) && i < len(lb); i++ {
		if la[i] != lb[i] {
			return i + 1
		}
	}
	return min(len(la), len(lb)) + 1
}

func diffContext(got, want string) string {
	n := firstDifference(got, want)
	line := func(text string) string {
		lines := strings.Split(text, "\n")
		if n-1 < len(lines) {
			return lines[n-1]
		}
		return "<end>"
	}
	return "got:  " + line(got) + "\nwant: " + line(want)
}
